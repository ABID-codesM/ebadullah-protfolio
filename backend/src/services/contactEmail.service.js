import transporter from "./mailer.js";

const escapeHTML = (value = "") => {
  return String(value).replace(/[&<>"']/g, (character) => {
    const entities = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };

    return entities[character];
  });
};

export const sendContactNotification = async (contact) => {
  const { fullName, email, subject, projectType, message } = contact;

  if (!process.env.CONTACT_RECEIVER) {
    throw new Error("CONTACT_RECEIVER is not configured.");
  }

  const safeName = escapeHTML(fullName);
  const safeEmail = escapeHTML(email);
  const safeSubject = escapeHTML(subject);
  const safeProjectType = escapeHTML(projectType);
  const safeMessage = escapeHTML(message).replace(/\n/g, "<br>");

  const mailOptions = {
    from: {
      name: "Portfolio Contact System",
      address: process.env.SMTP_USER,
    },

    to: process.env.CONTACT_RECEIVER,

    replyTo: email,

    subject: `New Portfolio Message: ${subject}`,

    text: `
New Contact Message

Name: ${fullName}
Email: ${email}
Subject: ${subject}
Project Type: ${projectType}

Message:
${message}
    `,

    html: `
      <div style="
        max-width: 650px;
        margin: auto;
        padding: 25px;
        font-family: Arial, sans-serif;
        color: #1f2937;
        background: #f8fafc;
        border-radius: 12px;
      ">

        <h2 style="color: #0891b2;">
          New Portfolio Message
        </h2>

        <p>You have received a new message through your portfolio website.</p>

        <div style="
          background: white;
          padding: 20px;
          border-radius: 10px;
          border: 1px solid #e5e7eb;
        ">

          <p><strong>Name:</strong> ${safeName}</p>

          <p><strong>Email:</strong> ${safeEmail}</p>

          <p><strong>Subject:</strong> ${safeSubject}</p>

          <p><strong>Project Type:</strong> ${safeProjectType}</p>

          <hr style="border: 0; border-top: 1px solid #e5e7eb;" />

          <h3>Message</h3>

          <p style="line-height: 1.7;">
            ${safeMessage}
          </p>

        </div>

        <p style="font-size: 12px; color: #64748b; margin-top: 20px;">
          This notification was automatically generated by your portfolio website.
        </p>

      </div>
    `,
  };

  return transporter.sendMail(mailOptions);
};
